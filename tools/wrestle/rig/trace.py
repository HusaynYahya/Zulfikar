"""Trace rigid pieces (head, hands, shoes) from a line drawing into vector shapes.
Each piece: a closed outline (centre of the drawn line) + interior detail strokes,
in piece-local coordinates: origin at the pivot, x-axis along the reference direction."""
import cv2, numpy as np, json, sys, math
from skimage.morphology import skeletonize

def load(path, flip=False):
    g = cv2.imread(path, 0)
    return cv2.flip(g, 1) if flip else g

def region(g, seed, clip=None, thr=140):
    ink = (g < thr).astype(np.uint8)
    free = (1 - ink).astype(np.uint8)
    if clip is not None:
        m = np.zeros_like(free); cv2.fillPoly(m, [np.array(clip, np.int32)], 1)
        free = free & m
    ff = free.copy() * 255
    seeds = seed if isinstance(seed[0], (list, tuple)) else [seed]
    for sd in seeds:
        mask = np.zeros((g.shape[0] + 2, g.shape[1] + 2), np.uint8)
        cv2.floodFill(ff, mask, tuple(int(v) for v in sd), 128)
    reg = (ff == 128).astype(np.uint8)
    # close over the inner lines that split a piece into regions (the hairline)
    reg = cv2.morphologyEx(reg, cv2.MORPH_CLOSE, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (11, 11)))
    # fill small holes (finger gaps etc.) and grow onto the middle of the drawn line
    reg = cv2.morphologyEx(reg, cv2.MORPH_CLOSE, np.ones((5, 5), np.uint8))
    reg = cv2.dilate(reg, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (5, 5)))
    if clip is not None:
        m = np.zeros_like(reg); cv2.fillPoly(m, [np.array(clip, np.int32)], 1); reg &= m
    return reg, ink

def outline(reg, eps=1.0):
    cs, _ = cv2.findContours(reg, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    c = max(cs, key=cv2.contourArea)
    c = cv2.approxPolyDP(c, eps, True)[:, 0, :].astype(float)
    return c

def details(reg, ink, minlen=12):
    """Ink strictly inside the region: the inner lines (hairline, ear, finger lines)."""
    inner = cv2.erode(reg, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (13, 13)))
    sk = skeletonize((ink & inner).astype(bool)).astype(np.uint8)
    # trace pixel chains
    pts = set(zip(*np.nonzero(sk)))
    nb = lambda p: [(p[0] + dy, p[1] + dx) for dy in (-1, 0, 1) for dx in (-1, 0, 1) if (dy or dx) and (p[0] + dy, p[1] + dx) in pts]
    paths = []
    ends = [p for p in pts if len(nb(p)) == 1]
    def walk(start):
        path = [start]; pts.discard(start); cur = start
        while True:
            n = [q for q in nb(cur)]
            if not n: break
            cur = n[0]; pts.discard(cur); path.append(cur)
        return path
    for e in ends:
        if e in pts: paths.append(walk(e))
    while pts: paths.append(walk(next(iter(pts))))
    out = []
    for p in paths:
        if len(p) < minlen: continue
        a = np.array([[x, y] for y, x in p], np.float32).reshape(-1, 1, 2)
        a = cv2.approxPolyDP(a, 1.0, False)[:, 0, :].astype(float)
        out.append(a)
    return out

def to_local(pts, pivot, ang):
    c, s = math.cos(-ang), math.sin(-ang)
    d = pts - np.array(pivot, float)
    return np.stack([d[:, 0] * c - d[:, 1] * s, d[:, 0] * s + d[:, 1] * c], 1)

if __name__ == "__main__":
    spec = json.load(open(sys.argv[1]))
    out, vis = {}, None
    for name, p in spec["pieces"].items():
        g = load(p["src"], p.get("flip", False))
        if vis is None: vis = cv2.cvtColor(g, cv2.COLOR_GRAY2BGR) // 2 + 127
        reg, ink = region(g, p["seed"], p.get("clip"))
        o = outline(reg)
        ds = details(reg, ink, p.get("minlen", 12)) if p.get("details", True) else []
        a, b = np.array(p["ref"][0], float), np.array(p["ref"][1], float)
        ang = math.atan2(b[1] - a[1], b[0] - a[0])
        out[name] = {"outline": np.round(to_local(o, p["pivot"], ang), 1).tolist(),
                     "details": [np.round(to_local(d, p["pivot"], ang), 1).tolist() for d in ds]}
        cv2.polylines(vis, [o.astype(np.int32)], True, (0, 0, 255), 2)
        for d in ds: cv2.polylines(vis, [d.astype(np.int32)], False, (255, 0, 0), 2)
        cv2.circle(vis, tuple(int(v) for v in p["pivot"]), 5, (0, 160, 0), -1)
        print(name, len(o), "outline pts,", len(ds), "detail strokes")
    json.dump(out, open(spec["out"], "w"))
    if spec.get("js"):          # the copy the page loads
        open(spec["js"], "w").write(
            "/* Generated by tools/wrestle/rig/trace.py from the stance drawing — the head, hands and shoe\n"
            "   as vector shapes in piece-local coordinates. Do not edit by hand. */\n"
            "window.ZRigPieces = " + json.dumps(out, separators=(",", ":")) + ";\n")
    x0, y0, x1, y1 = spec["crop"]
    cv2.imwrite(spec["vis"], vis[y0:y1, x0:x1])
